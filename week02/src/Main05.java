package main;

public class Main05 {
    public static void main(String[] args) {
        // A remainder of zero after division by 2 means the number is even.
        int x;
        x = 11;
        if(x % 2 == 0){
            System.out.println("The number is even");
        }
        else{
            System.out.println("The number is odd");
        }
    }
}
